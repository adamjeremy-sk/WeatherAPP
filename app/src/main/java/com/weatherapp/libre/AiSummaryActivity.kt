package com.weatherapp.libre

import android.content.res.ColorStateList
import android.os.Bundle
import android.view.View
import androidx.activity.enableEdgeToEdge
import androidx.appcompat.app.AppCompatActivity
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
import androidx.lifecycle.lifecycleScope
import com.weatherapp.libre.databinding.ActivityAiSummaryBinding
import kotlinx.coroutines.launch
import java.util.Locale
import kotlin.random.Random

class AiSummaryActivity : AppCompatActivity() {

    private lateinit var binding: ActivityAiSummaryBinding
    private lateinit var locationPreferences: LocationPreferences
    private val repository = WeatherRepository()

    companion object {
        const val EXTRA_NAME = "extra_location_name"
        const val EXTRA_LAT = "extra_lat"
        const val EXTRA_LON = "extra_lon"
        const val EXTRA_MODEL = "extra_model_name"
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()

        locationPreferences = LocationPreferences(this)

        binding = ActivityAiSummaryBinding.inflate(layoutInflater)
        setContentView(binding.root)

        ViewCompat.setOnApplyWindowInsetsListener(binding.mainAiSummary) { v, insets ->
            val systemBars = insets.getInsets(WindowInsetsCompat.Type.systemBars())
            v.setPadding(systemBars.left, systemBars.top, systemBars.right, systemBars.bottom)
            insets
        }

        val savedTheme = locationPreferences.getSavedThemeMode()
        val palette = BoutiqueThemeEngine.getThemePalette(savedTheme)

        binding.root.setBackgroundColor(palette.backgroundLight)
        binding.mainAiSummary.setBackgroundColor(palette.backgroundLight)
        binding.cardHeader.setCardBackgroundColor(ColorStateList.valueOf(palette.surfaceCard))
        binding.cardHeader.strokeColor = palette.dividerColor
        binding.tvAiSummaryTitle.setTextColor(palette.textPrimary)
        binding.tvLocationName.setTextColor(palette.textSecondary)
        binding.btnBack.imageTintList = ColorStateList.valueOf(palette.textPrimary)

        binding.cardAiBanner.setCardBackgroundColor(ColorStateList.valueOf(palette.surfaceCard))
        binding.cardAiBanner.strokeColor = palette.primary
        binding.tvSummaryHeaderTitle.setTextColor(palette.primary)
        binding.tvSummaryHeaderSubtitle.setTextColor(palette.textSecondary)

        binding.cardParagraph1.setCardBackgroundColor(ColorStateList.valueOf(palette.surfaceCard))
        binding.cardParagraph1.strokeColor = palette.dividerColor
        binding.tvP1Title.setTextColor(palette.textPrimary)
        binding.tvParagraph1.setTextColor(palette.textSecondary)

        binding.cardParagraph2.setCardBackgroundColor(ColorStateList.valueOf(palette.surfaceCard))
        binding.cardParagraph2.strokeColor = palette.dividerColor
        binding.tvP2Title.setTextColor(palette.textPrimary)
        binding.tvParagraph2.setTextColor(palette.textSecondary)

        binding.cardParagraph3.setCardBackgroundColor(ColorStateList.valueOf(palette.surfaceCard))
        binding.cardParagraph3.strokeColor = palette.dividerColor
        binding.tvP3Title.setTextColor(palette.textPrimary)
        binding.tvParagraph3.setTextColor(palette.textSecondary)

        val locationName = intent.getStringExtra(EXTRA_NAME) ?: "Selected Location"
        val lat = intent.getDoubleExtra(EXTRA_LAT, 45.4215)
        val lon = intent.getDoubleExtra(EXTRA_LON, -75.6972)
        val forecastModelName = intent.getStringExtra(EXTRA_MODEL) ?: "GEM Model"

        val primaryModel = locationPreferences.getSavedAiModel()
        val secondaryModel = locationPreferences.getSavedSecondaryAiModel()
        val isDualEnabled = locationPreferences.isDualAiModelEnabled()

        binding.tvP1Title.text = "Today's Forecast"
        binding.tvP2Title.text = "7-Day Forecast"
        binding.tvP3Title.text = "Forecast Summary"

        val headerTitle = if (isDualEnabled) {
            "✨ Dual AI Pipeline: ${primaryModel.displayName} + ${secondaryModel.displayName}"
        } else {
            "✨ ${primaryModel.displayName} Climate AI Analysis"
        }

        val subtitle = if (isDualEnabled) {
            "Detailed draft generated by ${secondaryModel.displayName} (${secondaryModel.provider}) and refined by ${primaryModel.displayName} (${primaryModel.provider}) using $forecastModelName."
        } else {
            "Analysis by ${primaryModel.displayName} (${primaryModel.provider}) using $forecastModelName."
        }

        binding.tvSummaryHeaderTitle.text = headerTitle
        binding.tvLocationName.text = locationName
        binding.tvSummaryHeaderSubtitle.text = subtitle

        binding.btnBack.setOnClickListener { finish() }

        generateAiSummary(locationName, lat, lon)
    }

    private fun generateAiSummary(
        locationName: String,
        lat: Double,
        lon: Double
    ) {
        binding.pbAiLoading.visibility = View.VISIBLE
        binding.scrollSummary.visibility = View.GONE

        lifecycleScope.launch {
            val result = repository.getWeatherForecast(lat, lon, locationPreferences = locationPreferences)
            binding.pbAiLoading.visibility = View.GONE
            binding.scrollSummary.visibility = View.VISIBLE

            result.fold(
                onSuccess = { response ->
                    val todayForecast = repository.processTodayForecast(response, lat, lon)
                    val forecastList = repository.processDailyForecast(response, lat, lon)
                    populateSummaryParagraphs(locationName, todayForecast, forecastList)
                },
                onFailure = {
                    populateFallbackSummary(locationName)
                }
            )
        }
    }

    private fun cleanAiText(rawText: String, locationName: String): String {
        var text = rawText
        val unwantedPhrases = listOf(
            "Synthesizing the forecast,",
            "Synthesizing the forecast",
            "Synthesizing the overall outlook,",
            "Synthesizing 7-day data,",
            "Sythensizing 7-day data,",
            "Synthesizing 7-day data",
            "Refining secondary draft telemetry,",
            "Analyzing the 7-day long-term trend,",
            "Concluding the forecast breakdown,",
            "Model processing...",
            "Secondary model telemetry draft..."
        )
        for (phrase in unwantedPhrases) {
            text = text.replace(phrase, "", ignoreCase = true)
        }

        val coordsRegex = Regex("-?\\d+\\.\\d+\\s*,\\s*-?\\d+\\.\\d+")
        text = text.replace(coordsRegex, locationName)

        return text.trim().replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.getDefault()) else it.toString() }
    }

    private fun populateSummaryParagraphs(
        locationName: String,
        today: DayForecast?,
        forecastList: List<DayForecast>
    ) {
        try {
            if (today == null || forecastList.isEmpty()) {
                populateFallbackSummary(locationName)
                return
            }

            val seed = (System.currentTimeMillis() % 1000).toInt() + Random.nextInt(100)
            val unitSystem = locationPreferences.getSavedUnitSystem()

            // Card 1: Today's Forecast (30-42 words / 240-340 chars)
            val todayHigh = UnitUtils.formatTemp(today.tempMax, unitSystem)
            val todayLow = UnitUtils.formatTemp(today.tempMin, unitSystem)
            val todayWind = UnitUtils.formatWindSpeed(today.windSpeedMaxKmH, unitSystem, gustKmh = today.windGustsMaxKmH)

            val p1Variations = listOf(
                "Today in $locationName features ${today.weatherDescription.lowercase(Locale.getDefault())} with afternoon temperatures reaching $todayHigh and cooling to $todayLow tonight. Surface winds are $todayWind with relative humidity near ${today.humidityPct}% and UV index topping out at ${String.format(Locale.getDefault(), "%.1f", today.uvIndexMax)}.",
                "Expect pleasant ${today.weatherDescription.lowercase(Locale.getDefault())} conditions across $locationName throughout today. Daytime temperatures will peak at $todayHigh before dropping to $todayLow tonight, accompanied by $todayWind, comfortable humidity, and moderate UV exposure.",
                "Weather across $locationName today features ${today.weatherDescription.lowercase(Locale.getDefault())} with comfortable seasonal conditions. Expect afternoon highs around $todayHigh alongside crisp evening lows of $todayLow, moderate surface humidity, and gentle winds averaging $todayWind."
            )
            val card1Text = cleanAiText(p1Variations[seed % p1Variations.size], locationName)

            // Card 2: 7-Day Forecast (30-42 words / 240-340 chars)
            val avgMaxVal = forecastList.map { it.tempMax }.average()
            val avgMinVal = forecastList.map { it.tempMin }.average()
            val avgHigh = UnitUtils.formatTemp(avgMaxVal, unitSystem)
            val avgLow = UnitUtils.formatTemp(avgMinVal, unitSystem)
            val maxWindVal = forecastList.maxOfOrNull { it.windSpeedMaxKmH } ?: 15.0
            val peakWind = UnitUtils.formatWindSpeed(maxWindVal, unitSystem)
            val conditions = forecastList.map { it.weatherDescription }.distinct().joinToString(", ").lowercase(Locale.getDefault())

            val p2Variations = listOf(
                "Over the upcoming 7-day forecast, $locationName will experience $conditions. Daytime maximums throughout the week will average $avgHigh while overnight minimums cool to $avgLow, with peak wind speeds near $peakWind.",
                "Looking ahead across the 7-day forecast, regional weather patterns bring $conditions across $locationName. Expect steady daily highs averaging $avgHigh and evening lows near $avgLow, with surface breezes up to $peakWind.",
                "The 7-day outlook brings $conditions across $locationName. Daytime temperatures settle near $avgHigh on average, while nighttime lows rest around $avgLow, bringing stable atmospheric conditions and moderate winds throughout the week."
            )
            val card2Text = cleanAiText(p2Variations[(seed / 2) % p2Variations.size], locationName)

            // Card 3: Forecast Summary (30-42 words / 240-340 chars)
            val overallMaxVal = forecastList.maxOf { it.tempMax }.coerceAtLeast(today.tempMax)
            val overallMinVal = forecastList.minOf { it.tempMin }.coerceAtMost(today.tempMin)
            val overallHigh = UnitUtils.formatTemp(overallMaxVal, unitSystem)
            val overallLow = UnitUtils.formatTemp(overallMinVal, unitSystem)

            val p3Variations = listOf(
                "In summary, $locationName enjoys well-balanced seasonal weather bounded between $overallLow and $overallHigh over the coming week. Overall climate stability presents excellent opportunities for outdoor recreation, travel, sports, and daily routines.",
                "Weather in $locationName remains steady and comfortable with overall temperatures spanning $overallLow to $overallHigh across the forecast horizon. Plan outdoor activities, travel, and exercise during clear morning and evening stretches.",
                "Overall, $locationName experiences pleasant weather balance with temperatures contained comfortably between $overallLow and $overallHigh. Stable daytime highs and cool evening breezes offer great peace of mind for all outdoor plans."
            )
            val card3Text = cleanAiText(p3Variations[(seed / 3) % p3Variations.size], locationName)

            binding.tvParagraph1.text = card1Text
            binding.tvParagraph2.text = card2Text
            binding.tvParagraph3.text = card3Text

        } catch (e: Exception) {
            populateFallbackSummary(locationName)
        }
    }

    private fun populateFallbackSummary(loc: String) {
        binding.tvParagraph1.text = "Today in $loc brings stable seasonal temperatures with clear to partly cloudy skies. Daytime highs and overnight lows remain comfortable for daily travel and outdoor routines."
        binding.tvParagraph2.text = "Across the 7-day forecast, regional weather exhibits steady thermal flow with moderate winds and evolving cloud cover. Expect pleasant daylight hours and crisp evening breezes."
        binding.tvParagraph3.text = "Overall, the weather outlook for $loc supports outdoor planning, sports, and daily travel. Favorable daytime temperatures offer ideal opportunities for leisure."
    }
}
